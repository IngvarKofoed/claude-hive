// Resolves the app's version from git ONCE, at build time, inside the checkout,
// and writes it to packages/shared/src/version.ts for backend and frontend to import.
// The running app never calls git. See docs/ARCHITECTURE.md, Versioning.
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const target = fileURLToPath(new URL("../packages/shared/src/version.ts", import.meta.url));

const version =
  process.env.APP_VERSION ?? // a build outside a checkout can pass it in directly
  (() => {
    try {
      return execSync("git describe --tags --long --always --dirty", { cwd: repoRoot })
        .toString()
        .trim();
    } catch {
      return "0.0.0-unknown"; // not a checkout, or git missing: the bake step had nothing to read
    }
  })();

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// generated by scripts/gen-version.mjs — do not edit\nexport const APP_VERSION = ${JSON.stringify(version)};\n`,
);
console.log(`APP_VERSION = ${version}`);
